"""Upload an edited Concept workbook back into a staged release.

The reviewer downloads the canonical release-bulk-import workbook, edits
it locally in Excel, and uploads the same file here. The upload is applied
as ONE recorded review round through the existing release revision trail,
then remains staged for the explicit Master resume. Publication is still a
separate hold. There is deliberately no second import semantics: the
previous path (``/data/import``) silently NO-OPed content edits on existing
concepts and forked a duplicate row on a title edit, which is exactly the
divergence this module closes.

Matching is mechanical and loud:

* primarily by the identity tag the downloaded workbook itself embeds in
  the title cells (rebuilt from the same staged payload through the same
  ``transient_release_hierarchy`` that rendered the download — one
  authority for the tag);
* fallback, for a row whose tag was lost in editing, exact
  (topic, concept title) match against the staged records;
* unmatched Post concepts are refused with their sheet and row named.
  Explicit new Pre rows may be added, including to an empty original,
  after their chapter/lane identity is checked and their provenance recorded.
  Reviewer-added Post questions are accepted only through the explicit
  reviewed Types/Cases or Concept Details question surface and receive a
  stable question identity with provenance.

Concept fields travel through the existing editable field rules. Post
question membership, wording, dependencies and reviewed Type/Case/Concept
placement travel through the explicit question review projection; Pre
questions remain generated by the prerequisite lane. Other rendered audit
columns are ignored here.
"""
