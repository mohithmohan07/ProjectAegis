class WorkbookEditError(ValueError):
    """The uploaded workbook cannot be applied mechanically."""


def _is_release_concept_tag(tag: object) -> bool:
    """Whether a title tag is one of Aegis' own concept identities.

    Aegis' own tags have the lane/topic/concept grammar parsed by
    ``identity.minted_concept_ordinal``.  This is a mechanical grammar check;
    whether an identity belongs to this release is checked separately against
    the target chapter/lane and staged tag map.
    """

    value = str(tag or "").strip()
    return bool(value and identity.minted_concept_ordinal(value) is not None)


def _is_expected_pre_tag(
    db: Session,
    payload: Mapping[str, Any],
    tag: object,
) -> bool:
    """Recognize a chapter's own Pre tag used as display metadata.

    Corrected canonical workbooks may have been produced by the catalogue
    importer before this staged release existed.  Their concept titles carry
    the chapter's normal ``..._PrL_T##_C##`` tag even when no staged PRC id
    exists.  Such a tag can be accepted as an addition hint only when its
    chapter/lane prefix agrees with this job; a tag from another chapter or a
    stale arbitrary identity remains a refusal.
    """

    value = str(tag or "").strip()
    if not value or not _is_release_concept_tag(value):
        return False
    try:
        chapter_id = int(payload.get("target_chapter_id") or 0)
        chapter = db.get(models.Chapter, chapter_id)
        if chapter is None:
            return False
        chapter_key = identity.chapter_key(
            chapter, chapter_id=chapter_id, session=db,
        )
    except Exception:
        return False
    return value.startswith(
        f"{chapter_key}_{identity.LANE_PRE_TOKEN}_"
    )


def _fresh_pre_concept_ids(
    records: list[Any], count: int,
) -> list[str]:
    """Mint collision-free internal Pre ids without re-keying old rows."""

    used = {
        str(row.get("_pre_concept_id") or "").strip()
        for row in records
        if isinstance(row, Mapping)
    }
    output: list[str] = []
    number = 1
    while len(output) < count:
        candidate = f"PRC-{number:04d}"
        number += 1
        if candidate in used:
            continue
        used.add(candidate)
        output.append(candidate)
    return output


def _new_pre_record(
    row: Mapping[str, Any],
    pre_concept_id: str,
    *,
    round_stamp: str,
    owner_sub: str,
) -> dict[str, Any]:
    """Build a reviewer-added Pre row from authored cells only.

    The row deliberately carries no source block, semantic topic id, or
    prerequisite provenance: those values were not supplied by the reviewer.
    Empty lane-private collections are explicit so later Pre regeneration can
    key exactly on ``_pre_concept_id`` without treating the row as a source
    capture.
    """

    return {
        "topic": str(row.get("topic") or "").strip(),
        "parent_concept": str(row.get("parent_concept") or "").strip(),
        "concept_title": str(row.get("concept_title") or "").strip(),
        "concept_details": str(row.get("concept_details") or ""),
        "keywords": str(row.get("keywords") or "").strip(),
        "_pre_concept_id": pre_concept_id,
        "_reviewed_pre_identity_tag": str(row.get("tag") or "").strip(),
        "_aegis_pre_prerequisites": [],
        "_aegis_needed_for": [],
        "_aegis_pre_related_concepts": "",
        "_aegis_pre_related_concepts_unresolved": [],
        bcr.RELEASE_ROW_LANE_FIELD: bcr.LANE_PRE,
        bcr.RELEASE_ROW_STATUS_FIELD: "ready",
        bcr.RELEASE_ROW_ERRORS_FIELD: [],
        "review_flags": [
            "manual reviewer addition: Pre concept added from corrected workbook",
        ],
        bcr.MANUAL_EDIT_TRAIL_FIELD: [{
            "kind": "addition",
            "at": round_stamp,
            "editor": owner_sub or "local:default",
            "pre_concept_id": pre_concept_id,
        }],
    }


def _refresh_edited_validation_reports(
    candidate: dict[str, Any],
) -> None:
    """Refresh frozen output audits when the exported Concept fields changed.

    The reports are content receipts, so retaining one after a reviewer edits
    ``concept_details`` would make the next readiness check compare new bytes
    with an old receipt. Routing-only question edits do not change the
    exported Concept projection and therefore keep their existing reports.
    """
    from . import katex_render_validation, source_asset_publication

    exported = {
        "records": candidate.get("records") or [],
        "chapter_meta": candidate.get("chapter_meta") or {},
    }
    checks = (
        (source_asset_publication, "inputs_sha256"),
        (katex_render_validation, "input_sha256"),
    )
    issues = list(candidate.get("issues") or [])
    for checker, digest_key in checks:
        old = candidate.get(checker.REPORT_FIELD)
        refreshed = (
            checker.inspect_assets(exported)
            if checker is source_asset_publication
            else checker.inspect_render(exported)
        )
        changed = (
            not isinstance(old, Mapping)
            or old.get(digest_key) != refreshed.get(digest_key)
            or old.get("version") != refreshed.get("version")
        )
        if not changed:
            continue
        candidate[checker.REPORT_FIELD] = refreshed
        phase = "release_assets" if checker is source_asset_publication else "render"
        issues = [
            issue for issue in issues
            if not isinstance(issue, Mapping) or issue.get("phase") != phase
        ]
        issues.extend(checker.release_findings(refreshed))
    candidate["issues"] = issues


def _sheet_headers(wb) -> dict[str, tuple]:
    return {
        name: tuple(
            next(wb[name].iter_rows(min_row=2, max_row=2, values_only=True),
                 ()),
        )
        for name in wb.sheetnames
    }


def _record_titles(record: Mapping[str, Any]) -> tuple[str, str]:
    topic = str(record.get("topic") or "").strip()
    title = str(
        record.get("concept_title") or record.get("concept") or ""
    ).strip()
    return topic, title


def _staged_maps(
    db: Session, job: models.UploadJob, payload: Mapping[str, Any]
) -> tuple[dict[str, int], dict[tuple[str, str], list[int]]]:
    """(tag -> record_index, (topic, title) -> [record_index...]).

    The tag map is rebuilt through ``transient_release_hierarchy`` — the
    exact function that rendered the downloaded workbook — so the ids
    here are byte-identical to the tags the reviewer's file carries. The
    transient pass skips defective rows, so its (concept, record) pairs
    are re-anchored to payload record indexes by equality, consumed in
    order (duplicate-safe).
    """

    records = payload.get("records") or []
    by_title: dict[tuple[str, str], list[int]] = {}
    for index, record in enumerate(records):
        if isinstance(record, Mapping):
            by_title.setdefault(_record_titles(record), []).append(index)

    tag_map: dict[str, int] = {}
    try:
        _chapter, concepts, carried, _defects = (
            release_files.transient_release_hierarchy(
                db, job, payload=dict(payload)
            )
        )
    except Exception:
        # The tag join is an assist; title matching still works. A
        # payload the hierarchy refuses outright will be refused again,
        # loudly, by the publication step below.
        return {}, by_title
    consumed: set[int] = set()
    for concept, record in zip(concepts, carried):
        if not isinstance(record, Mapping):
            continue
        key = _record_titles(record)
        index = next(
            (
                candidate for candidate in by_title.get(key, [])
                if candidate not in consumed
                and records[candidate] == record
            ),
            None,
        )
        if index is None:
            index = next(
                (
                    candidate for candidate in by_title.get(key, [])
                    if candidate not in consumed
                ),
                None,
            )
        if index is None:
            continue
        consumed.add(index)
        tag = str(getattr(concept, "machine_id", "") or "").strip()
        if tag and tag not in tag_map:
            tag_map[tag] = index
    return tag_map, by_title


def _workbook_rows(path: Path) -> list[dict[str, Any]]:
    """Every content row's topic/concept projection, layout-identified."""

    wb = openpyxl.load_workbook(path, data_only=True, read_only=True)
    try:
        if (
            "Released Concepts" in wb.sheetnames
            and str(wb["Released Concepts"].cell(1, 1).value or "")
            == "Release Row"
        ):
            ws = wb["Released Concepts"]
            headers = {
                str(value or "").strip().casefold(): index
                for index, value in enumerate(
                    next(ws.iter_rows(min_row=1, max_row=1, values_only=True), ())
                )
            }
            rows: list[dict[str, str]] = []
            for row_i, values in enumerate(
                ws.iter_rows(min_row=2, values_only=True), start=2
            ):
                if not values or not any(value not in (None, "") for value in values):
                    continue
                cell = lambda name: values[headers[name]] if headers.get(name, -1) < len(values) else ""
                raw_title = str(cell("concept title") or "")
                if not raw_title.strip():
                    continue
                rows.append({
                    "sheet": "Released Concepts",
                    "row": str(row_i),
                    "tag": identity.title_tag(raw_title),
                    "topic": str(cell("topic") or "").strip(),
                    "concept_title": strip_title_tag(raw_title).strip(),
                    "parent_concept": str(cell("parent concept") or "").strip(),
                    "concept_details": str(cell("concept details") or ""),
                    "concept_details_raw": str(cell("concept details") or ""),
                    "keywords": str(cell("keywords") or "").strip(),
                })
            return rows
        identified = layouts.identify_workbook(_sheet_headers(wb))
        rows: list[dict[str, str]] = []
        for found in identified.sheets:
            ws = wb[found.sheet_name]
            for row_i, row in enumerate(
                ws.iter_rows(min_row=3, values_only=True), start=3
            ):
                if row is None or not any(row):
                    continue
                top = found.sheet.block_values(row, "topic")
                con = found.sheet.block_values(row, "concept")
                raw_title = str(con.get("concept_title") or "")
                if not raw_title.strip():
                    continue
                rows.append({
                    "sheet": found.sheet_name,
                    "row": str(row_i),
                    "tag": identity.title_tag(raw_title),
                    "topic": strip_topic_title(
                        str(top.get("topic_title") or "")
                    ).strip(),
                    "concept_title": strip_title_tag(raw_title).strip(),
                    "parent_concept": str(
                        con.get("parent_concept") or ""
                    ).strip(),
                    "concept_details": str(
                        con.get("concept_details") or ""
                    ),
                    "concept_details_raw": str(
                        con.get("concept_details") or ""
                    ),
                    "keywords": str(con.get("keywords") or "").strip(),
                })
        from .concept_workbook_rows import coalesce_repeated_sheet_rows
        return coalesce_repeated_sheet_rows(rows)
    finally:
        wb.close()


